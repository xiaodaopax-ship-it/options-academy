  Q.generatorsCn = gens;
  Q.generateCn = function (n) {
    const out = [];
    for (let i = 0; i < n; i++) out.push(gens[i % gens.length]());
    for (let i = out.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [out[i], out[j]] = [out[j], out[i]];
    }
    return out;
  };
