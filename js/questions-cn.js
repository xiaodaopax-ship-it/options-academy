  // ---------- CNY calculation generators ----------
  const r4 = (v) => Math.round(v * 10000) / 10000;
  const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
  const rndStep = (a, b, step) => r4(Math.round((a + Math.random() * (b - a)) / step) * step);
  const yuan = (v) => {
    const a = Math.abs(Math.round(v * 100) / 100);
    const d = Number.isInteger(a) ? 0 : 2;
    return (v < -0.005 ? '−' : '') + a.toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d }) + ' 元';
  };
  const plY = (v) => (Math.abs(v) < 0.005 ? '0 元' : (v > 0 ? '+' : '') + yuan(v));
  const p4 = (v) => v.toFixed(4);
  const p3 = (v) => v.toFixed(3);
  const M = 10000;
  let seq = 0;
  const newId = () => 'gc' + Date.now().toString(36) + (seq++).toString(36);

  function mcq(q, correct, distractors, e, format, padStep) {
    const seen = new Set([format(correct)]);
    const opts = [format(correct)];
    for (const d of distractors) {
      const s = format(d);
      if (!seen.has(s)) { seen.add(s); opts.push(s); }
      if (opts.length === 4) break;
    }
    let k = 1;
    while (opts.length < 4) {
      const s = format(correct + (k % 2 ? 1 : -1) * Math.ceil(k / 2) * padStep);
      if (!seen.has(s)) { seen.add(s); opts.push(s); }
      k++;
    }
    return { id: newId(), ch: 'calc-cn', gen: true, q, o: opts, a: 0, e };
  }

